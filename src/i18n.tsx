const exact = (s:string) => ru[s] ?? s;

export function translateText(text:string, lang:Language):string {
  if (lang==='en') return text;
  if (ru[text]) return ru[text];
  let m:RegExpMatchArray|null;
  if ((m=text.match(/^(\d+) rows$/))) return `${m[1]} строк`;
  if ((m=text.match(/^Calculate window for (.+)$/))) return `Рассчитать окно для ${m[1]}`;
  if ((m=text.match(/^Current row: (.+)$/))) return `Текущая строка: ${m[1]}`;
  if ((m=text.match(/^Assign (.+) to (.+)$/))) return `Назначить ${m[1]} для ${m[2]}`;
  if ((m=text.match(/^Count the (.+) partition$/))) return `Посчитать партицию ${m[1]}`;
  if ((m=text.match(/^(.+) complete$/))) return `${m[1]} завершён`;
  return exact(text);
}

type Ctx={lang:Language;setLang:(l:Language)=>void;t:(s:string)=>string};
const LanguageContext=createContext<Ctx>({lang:'en',setLang:()=>{},t:s=>s});

export function LanguageProvider({children}:{children:ReactNode}){
  const [lang,setLangState]=useState<Language>(()=>localStorage.getItem('toolkit-language')==='ru'?'ru':'en');
  const setLang=(next:Language)=>setLangState(next);
  useEffect(()=>{localStorage.setItem('toolkit-language',lang);document.documentElement.lang=lang},[lang]);
  const value=useMemo(()=>({lang,setLang,t:(s:string)=>translateText(s,lang)}),[lang]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(){return useContext(LanguageContext)}
